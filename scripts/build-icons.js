// icons/sprite.svg (source of truth) -> edgelit-icons.js (injects the sprite into the page).
// External <use href="icons.svg#i-x"> is blocked on file:// and cross-origin, so the sprite is injected inline by script instead.
//   npm run build:icons
// Load it as the first child of <body> (the sprite then exists before page scripts run); in <head> it injects at DOMContentLoaded.
const fs = require('fs'); const path = require('path');
const root = path.resolve(__dirname, '..');
function build() {
  const src = fs.readFileSync(path.join(root, 'icons', 'sprite.svg'), 'utf8');
  const symbols = (src.match(/<symbol[\s\S]*?<\/symbol>/g) || []).map(s => s.replace(/\s+/g, ' ').replace(/> </g, '><')).join('');
  return `/* GENERATED by scripts/build-icons.js from icons/sprite.svg. Do not edit by hand. */
(function () {
  var svg = '<svg id="me-icons" xmlns="http://www.w3.org/2000/svg" width="0" height="0" style="position:absolute" aria-hidden="true" focusable="false"><defs>${symbols}</defs></svg>';
  function add() { if (!document.getElementById('me-icons')) document.body.insertAdjacentHTML('afterbegin', svg); }
  if (document.body) add(); else document.addEventListener('DOMContentLoaded', add);
})();
`;
}
if (require.main === module) { fs.writeFileSync(path.join(root, 'edgelit-icons.js'), build()); console.log('edgelit-icons.js written'); }
module.exports = { build };
