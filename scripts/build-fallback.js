// color-mix() fallback for browsers without it (Safari < 16.2, Firefox < 113).
// Every declaration in monoedge.css that uses  color-mix(in srgb, var(--X) P, transparent)  is re-emitted under
//   @supports not (color: color-mix(in srgb, red, blue)) { ... }
// as  rgb(var(--X-rgb) / P). That is exactly what an alpha mix with transparent means, so the result is the same colour.
// The -rgb channel triplets come from the token build (dist/tokens.css) and from the signal scopes in monoedge.css.
// Output: dist/fallback.css (imported by monoedge.css). Custom properties are re-declared too: a var() holding an unsupported color-mix is
// "invalid at computed-value time" and would NOT fall back to an earlier declaration.
//   npm run build:fallback          write dist/fallback.css
//   node scripts/build-fallback.js --check   fail if it is out of date or a color-mix could not be converted
const fs = require('fs'); const path = require('path'); const postcss = require('postcss');
const root = path.resolve(__dirname, '..');
const SUPPORTS = '(color: color-mix(in srgb, red, blue))';

/** Replace color-mix(in srgb, var(--x) <pct>, transparent) with rgb(var(--x-rgb) / <pct>). Handles nested parentheses in <pct> (calc). Returns null if anything else remains. */
function convert(value) {
  let out = '', i = 0, bad = false;
  while (i < value.length) {
    const at = value.indexOf('color-mix(', i);
    if (at < 0) { out += value.slice(i); break; }
    out += value.slice(i, at);
    let depth = 0, j = at + 'color-mix'.length;
    for (; j < value.length; j++) { if (value[j] === '(') depth++; else if (value[j] === ')' && --depth === 0) break; }
    const inner = value.slice(at + 'color-mix('.length, j);
    const m = /^in srgb,\s*var\((--[\w-]+)\)\s+([\s\S]+?),\s*transparent$/.exec(inner.trim());
    if (m) out += `rgb(var(${m[1]}-rgb) / ${m[2].trim()})`; else { bad = true; out += value.slice(at, j + 1); }
    i = j + 1;
  }
  return bad ? null : out;
}

function build() {
  const src = fs.readFileSync(path.join(root, 'monoedge.css'), 'utf8');
  const tree = postcss.parse(src), groups = new Map(), problems = [];
  tree.walkDecls(d => {
    if (!d.value.includes('color-mix(')) return;
    const v = convert(d.value);
    if (v === null) { problems.push(`${d.parent.selector ?? ''} { ${d.prop}: ${d.value} }`); return; }
    const chain = []; for (let p = d.parent.parent; p && p.type !== 'root'; p = p.parent) if (p.type === 'atrule' && p.name !== 'layer') chain.unshift(`@${p.name} ${p.params}`);
    const key = chain.join('\u0001') + '\u0002' + d.parent.selector;
    (groups.get(key) ?? groups.set(key, { chain, selector: d.parent.selector, decls: new Map() }).get(key)).decls.set(d.prop, v);
  });
  const lines = [];
  for (const g of groups.values()) {
    const pad = n => '  '.repeat(n); let depth = 2;
    for (const c of g.chain) { lines.push(pad(depth) + c + ' {'); depth++; }
    lines.push(pad(depth) + g.selector.replace(/\s+/g, ' ') + ' {');
    for (const [prop, val] of g.decls) lines.push(pad(depth + 1) + `${prop}: ${val};`);
    lines.push(pad(depth) + '}');
    for (let k = 0; k < g.chain.length; k++) { depth--; lines.push(pad(depth) + '}'); }
  }
  const css = `/* GENERATED by scripts/build-fallback.js from monoedge.css. Do not edit by hand.
   Only applies where color-mix() is unsupported. In the highest layer so it wins over the (dropped or invalid) originals. */
@layer utilities {
  @supports not ${SUPPORTS} {
${lines.join('\n')}
  }
}
`;
  return { css, problems, count: groups.size };
}

module.exports = { build, convert, SUPPORTS };
if (require.main === module) {
  const { css, problems, count } = build(), file = path.join(root, 'dist', 'fallback.css');
  if (problems.length) { console.error('color-mix usages the fallback cannot convert (only "in srgb, var(--x) P, transparent" is supported):\n  ' + problems.join('\n  ')); process.exit(1); }
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== css) { console.error('dist/fallback.css is out of date (run npm run build:fallback)'); process.exit(1); }
    console.log('fallback: dist/fallback.css is current (' + count + ' rules)'); process.exit(0);
  }
  fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, css);
  console.log('fallback built: ' + count + ' rules -> dist/fallback.css');
}
