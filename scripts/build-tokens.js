// Design tokens: tokens/*.tokens.json (W3C DTCG format, one source of truth) -> Style Dictionary -> dist/
//   dist/tokens.css          custom properties (loaded by monoedge.css into the `tokens` layer)
//   dist/tokens.js           resolved values for JS (both themes)
//   dist/tokens.json         the same as plain JSON
//   dist/tailwind.preset.js  Tailwind preset that points at the CSS variables
// Signal colours are authored in OKLCH and emitted as hex. Before anything is written, every theme goes through the accessibility gate
// (4.5:1 text, 3:1 graphics); the build fails if a pair does not pass.
//   npm run build:tokens           write dist/
//   node scripts/build-tokens.js --check   fail if dist/ is out of date (used by tests)
const fs = require('fs'); const path = require('path');
const { hexOf, gate } = require('./colors');
const root = path.resolve(__dirname, '..');
const read = f => JSON.parse(fs.readFileSync(path.join(root, 'tokens', f), 'utf8'));

/** oklch(...) strings -> hex, everything else untouched. */
function resolveColours(node) {
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith('$') && k !== '$value') continue;
    if (k === '$value' && typeof v === 'string' && v.startsWith('oklch(')) node.$value = hexOf(v);
    else if (v && typeof v === 'object') resolveColours(v);
  }
  return node;
}
const cssName = path => '--' + path.filter((p, i, a) => !(p === 'base' && i === a.length - 1)).join('-');
const flat = (obj, p = []) => Object.entries(obj).flatMap(([k, v]) => k.startsWith('$') ? [] : (v && typeof v === 'object' && '$value' in v) ? [[[...p, k], v.$value]] : flat(v, [...p, k]));
const lookup = (theme, ...p) => p.reduce((o, k) => o?.[k], theme)?.$value;

function themeForGate(name, t, mode) {
  const g = (...p) => lookup(t, ...p);
  const signals = Object.fromEntries(['accent', 'ok', 'warn', 'err', 'info'].map(k => [k, { fill: g(k, 'base'), text: g(k, 'text') }]));
  return {
    mode,
    surfaces: { canvas: g('color', 'canvas'), panel: g('color', 'panel'), surface: g('color', 'surface'), overlay: g('color', 'overlay') },
    text: { primary: g('color', 'text', 'primary'), muted: g('color', 'text', 'muted'), dim: g('color', 'text', 'dim') },
    strokes: { 'stroke-control': g('stroke', 'control'), 'tick-idle': g('tick-idle') },
    signals,
    // dark: filled status badge = signal fill + dark ink. light: badge fills with the signal TEXT colour and white ink (see .me-badge--fill in monoedge.css)
    onFill: mode === 'dark' ? g('on-signal') : '#ffffff',
    filledBadgeBg: mode === 'dark' ? undefined : sg => sg.text,
  };
}

async function build({ check = false } = {}) {
  const SD = (await import('style-dictionary')).default;
  const tokens = { core: resolveColours(read('core.tokens.json')), dark: resolveColours(read('dark.tokens.json')), light: resolveColours(read('light.tokens.json')) };

  const fails = [...gate('dark', themeForGate('dark', tokens.dark, 'dark')), ...gate('light', themeForGate('light', tokens.light, 'light'))];

  const out = {};
  const groups = dictionary => {
    const g = { core: [], dark: [], light: [] };
    for (const t of dictionary.allTokens) g[t.path[0]].push({ path: t.path.slice(1), value: t.$value ?? t.value, type: t.$type ?? t.type, desc: t.$description });
    return g;
  };
  // every opaque colour also gets a "-rgb" channel triplet: it is what the color-mix() fallback (dist/fallback.css) builds alpha colours from
  const rgbTriplet = hex => { const m = /^#([0-9a-f]{6})$/i.exec(String(hex)); return m ? [0, 2, 4].map(i => parseInt(m[1].slice(i, i + 2), 16)).join(' ') : null; };
  const decl = t => `  ${cssName(t.path)}: ${t.value};${t.desc ? `   /* ${t.desc} */` : ''}` + (t.type === 'color' && rgbTriplet(t.value) ? `\n  ${cssName(t.path)}-rgb: ${rgbTriplet(t.value)};` : '');
  const block = (sel, scheme, list) => `${sel} {\n${scheme ? `  color-scheme: ${scheme};\n` : ''}${list.map(decl).join('\n')}\n}\n`;
  const head = '/* GENERATED by scripts/build-tokens.js from tokens/*.tokens.json (W3C DTCG). Do not edit by hand. */\n';
  const nest = list => list.reduce((o, t) => { t.path.reduce((n, k, i, a) => (i === a.length - 1 ? (n[k] = t.value) : (n[k] ||= {})), o); return o; }, {});

  const sd = new SD({
    tokens, log: { verbosity: 'silent' },
    hooks: {
      formats: {
        'monoedge/css': ({ dictionary }) => { const g = groups(dictionary); return head + block(':root', '', g.core) + '\n' + block(':root, [data-theme="dark"]', 'dark', g.dark) + '\n' + block('[data-theme="light"]', 'light', g.light); },
        'monoedge/json': ({ dictionary }) => { const g = groups(dictionary); return JSON.stringify({ core: nest(g.core), dark: nest(g.dark), light: nest(g.light) }, null, 2) + '\n'; },
        'monoedge/js': ({ dictionary }) => {
          const g = groups(dictionary); const vars = {};
          for (const th of ['dark', 'light']) for (const t of g[th]) (vars[cssName(t.path)] ||= {})[th] = t.value;
          for (const t of g.core) vars[cssName(t.path)] = t.value;
          return `/* GENERATED by scripts/build-tokens.js. Do not edit by hand. */\nmodule.exports = ${JSON.stringify({ core: nest(g.core), dark: nest(g.dark), light: nest(g.light), cssVars: vars }, null, 2)};\n`;
        },
        'monoedge/tailwind': ({ dictionary }) => {
          const g = groups(dictionary), v = n => `var(${n})`, names = list => Object.fromEntries(list.map(t => [t.path.join('-'), v(cssName(t.path))]));
          const sig = k => ({ DEFAULT: v(`--${k}`), text: v(`--${k}-text`) });
          const preset = {
            theme: { extend: {
              colors: { canvas: v('--color-canvas'), panel: v('--color-panel'), surface: v('--color-surface'), overlay: v('--color-overlay'), ink: { DEFAULT: v('--color-text-primary'), muted: v('--color-text-muted'), dim: v('--color-text-dim') }, accent: sig('accent'), ok: sig('ok'), warn: sig('warn'), err: sig('err'), info: sig('info') },
              spacing: Object.fromEntries(g.core.filter(t => t.path[0] === 'space').map(t => [t.path[1], v(cssName(t.path))])),
              borderRadius: Object.fromEntries(g.core.filter(t => t.path[0] === 'radius').map(t => [t.path[1], v(cssName(t.path))])),
              fontFamily: { ui: [v('--font-ui')], display: [v('--font-display')] },
              zIndex: Object.fromEntries(g.core.filter(t => t.path[0] === 'z').map(t => [t.path[1], v(cssName(t.path))])),
              transitionDuration: { DEFAULT: v('--dur') }, transitionTimingFunction: { DEFAULT: v('--ease') },
            } },
          };
          return `/* GENERATED by scripts/build-tokens.js. Tailwind preset: colours and sizes point at the CSS variables, so both themes work. */\nmodule.exports = ${JSON.stringify(preset, null, 2)};\n`;
        },
      },
    },
    platforms: { dist: { transforms: [], buildPath: 'dist/', files: [
      { destination: 'tokens.css', format: 'monoedge/css' }, { destination: 'tokens.json', format: 'monoedge/json' },
      { destination: 'tokens.js', format: 'monoedge/js' }, { destination: 'tailwind.preset.js', format: 'monoedge/tailwind' },
    ] } },
  });
  const platformTokens = await sd.getPlatformTokens('dist');
  const files = {};
  for (const f of sd.platforms?.dist?.files ?? [{ destination: 'tokens.css' }]) void f;
  // render each file with its format
  const formats = sd.hooks?.formats ?? {};
  const names = { 'tokens.css': 'monoedge/css', 'tokens.json': 'monoedge/json', 'tokens.js': 'monoedge/js', 'tailwind.preset.js': 'monoedge/tailwind' };
  for (const [file, fmt] of Object.entries(names)) files[file] = await formats[fmt]({ dictionary: platformTokens, platform: {}, options: {}, file: { destination: file } });

  const dist = path.join(root, 'dist');
  if (check) {
    const stale = Object.entries(files).filter(([f, c]) => !fs.existsSync(path.join(dist, f)) || fs.readFileSync(path.join(dist, f), 'utf8') !== c).map(([f]) => f);
    return { fails, stale, files };
  }
  fs.mkdirSync(dist, { recursive: true });
  if (!fails.length) for (const [f, c] of Object.entries(files)) fs.writeFileSync(path.join(dist, f), c);
  return { fails, stale: [], files };
}

module.exports = { build, themeForGate, resolveColours };
if (require.main === module) {
  build({ check: process.argv.includes('--check') }).then(({ fails, stale }) => {
    if (fails.length) { console.error('Token accessibility gate FAILED:\n  ' + fails.join('\n  ')); process.exit(1); }
    if (stale.length) { console.error('dist/ is out of date: ' + stale.join(', ') + '  (run npm run build:tokens)'); process.exit(1); }
    console.log(process.argv.includes('--check') ? 'tokens: dist/ is current, gate passes' : 'tokens built: dist/tokens.css, tokens.js, tokens.json, tailwind.preset.js (gate passes)');
  });
}
